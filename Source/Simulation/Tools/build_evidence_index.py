"""Machine-generated evidence index for the diagnostics run.

Usage: python Tools/build_evidence_index.py <DiagnosticsDir>
Reads every scenario *.jsonl (excluding the T02 neutrality dump) and writes
<DiagnosticsDir>/transition_index.md : every distinct (pool, field, old -> new, system, op)
transition with occurrence count and the first file:line where it was observed,
plus <DiagnosticsDir>/scenario_summary.md : the summary marker of every scenario.
Nothing here is hand-written; values come from the JSONL emitted by SimDiagnostics.
"""
import json, os, sys, collections

D = sys.argv[1] if len(sys.argv) > 1 else "Diagnostics"


def fmt(v):
    if v is None:
        return "∅"
    return str(v)


def main():
    files = sorted(f for f in os.listdir(D) if f.endswith(".jsonl") and not f.startswith("T02"))
    agg = collections.OrderedDict()
    fields_changed = collections.OrderedDict()
    summaries = []
    systems = collections.OrderedDict()
    for fn in files:
        with open(os.path.join(D, fn), encoding="utf-8") as f:
            for ln, line in enumerate(f, 1):
                line = line.strip()
                if not line:
                    continue
                r = json.loads(line)
                t = r.get("type")
                if t == "summary":
                    summaries.append(r)
                elif t == "system":
                    systems.setdefault((r["order"], r["system"]), 0)
                    systems[(r["order"], r["system"])] += 1
                elif t in ("transition", "change"):
                    ent = r.get("entity", r.get("match"))
                    fk = (r["pool"], r["field"], r["system"], r["op"])
                    if fk not in fields_changed:
                        fields_changed[fk] = [0, f"{fn}:{ln}"]
                    fields_changed[fk][0] += 1
                    if t == "transition":
                        old = r.get("oldName") if r.get("oldName") is not None else r.get("old")
                        new = r.get("newName") if r.get("newName") is not None else r.get("new")
                        if r["op"] == "add":
                            old = None
                        if r["op"] == "remove":
                            new = None
                        key = (r["pool"], r["field"], fmt(old), fmt(new), r["system"], r["op"])
                        if key not in agg:
                            agg[key] = [0, f"{fn}:{ln}", r["tick"], set()]
                        agg[key][0] += 1
                        agg[key][3].add(ent)

    with open(os.path.join(D, "transition_index.md"), "w", encoding="utf-8") as o:
        o.write("# Transition index (machine-generated by Tools/build_evidence_index.py)\n\n")
        o.write("Source: every scenario JSONL in this directory. `∅` = absent (intent add/remove).\n")
        o.write("Ticks are 0-based simulation ticks of the scenario run (reset at scenario start).\n\n")
        o.write("| pool | field | old | new | system | op | count | keys | first evidence (file:line, tick) |\n")
        o.write("|---|---|---|---|---|---|---|---|---|\n")
        for k, v in agg.items():
            keys = ",".join(str(x) for x in sorted(v[3], key=lambda z: (z is None, z)))
            o.write(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {k[4]} | {k[5]} | {v[0]} | {keys} | {v[1]} t={v[2]} |\n")
        o.write("\n## Every (pool, field, writer system, op) observed changing\n\n")
        o.write("| pool | field | writer system | op | count | first evidence |\n|---|---|---|---|---|---|\n")
        for k, v in fields_changed.items():
            o.write(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {v[0]} | {v[1]} |\n")
        o.write("\n## System execution order observed (order index, name, records)\n\n")
        o.write("| order | system | system records |\n|---|---|---|\n")
        for (order, name), c in sorted(systems.items()):
            o.write(f"| {order} | {name} | {c} |\n")

    with open(os.path.join(D, "scenario_summary.md"), "w", encoding="utf-8") as o:
        o.write("# Scenario summaries (machine-generated from `summary` markers)\n\n")
        o.write("| scenario | ticks | final score L-R | points L/R | max touchCount | player actions | AI actions | player jumps | linear-trajectory ticks | NaN ticks | finished@tick |\n")
        o.write("|---|---|---|---|---|---|---|---|---|---|---|\n")
        for s in summaries:
            o.write(
                f"| {s['name']} | {s['ticks']} | {s['finalScore'][0]}-{s['finalScore'][1]} | {s['pointsLeft']}/{s['pointsRight']} | "
                f"{s['maxTouchCount']} | {json.dumps(s['playerActions'])} | {json.dumps(s['aiActions'])} | {s.get('playerJumps', 0)} | "
                f"{s['linearTrajectoryTicks']} | {s['nanTicks']} | {s['finishedAtTick'] if s['finished'] else '-'} |\n")
    print(f"transitions={len(agg)} fieldWriters={len(fields_changed)} scenarios={len(summaries)}")


if __name__ == "__main__":
    main()
